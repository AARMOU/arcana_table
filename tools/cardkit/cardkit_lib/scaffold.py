"""`cardkit newcard "Card Name"`: an honest starting point for one custom card.

Generates the definition file with only the mechanical facts filled in (name, cost, colour identity, type
line, stats, verbatim Oracle text, printing metadata, plain keywords already proven by tested cards) and a
scenario test that FAILS until real scenarios replace it. Every rules line is left as a CARDKIT-TODO with
the closest implemented references. `cardkit check` refuses to let a scaffold be registered.
"""
from __future__ import annotations

import re
from pathlib import Path

from . import oracle, patterns, readiness, refs, repo, sdk, text

WUBRG = "WUBRG"
RARITY = {"common": "COMMON", "uncommon": "UNCOMMON", "rare": "RARE", "mythic": "MYTHIC",
          "special": "SPECIAL", "bonus": "BONUS"}


def plain_keywords_verified() -> set[str]:
    """Keyword enum names that tested custom cards already pass to `keywords(...)`."""
    data = patterns.build() if not patterns.OUT_JSON.exists() else __import__("json").loads(
        patterns.OUT_JSON.read_text(encoding="utf-8"))
    return {k.split(".", 1)[1] for k in data.get("Keyword", {})}


def keyword_enum_name(word: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "_", word.upper()).strip("_")


def _keyword_line_names(line: str, card_keywords: list[str]) -> list[str] | None:
    """Enum names if [line] is only plain, verified, parameterless keywords; else None."""
    allowed = plain_keywords_verified() & sdk.keyword_enum()
    names = []
    for part in [p.strip() for p in line.split(",") if p.strip()]:
        if not any(part.casefold() == k.casefold() for k in card_keywords):
            return None
        enum = keyword_enum_name(part)
        if enum not in allowed:
            return None
        names.append(enum)
    return names or None


def render_card(card: dict, val: str) -> tuple[str, list[str]]:
    name = card["name"]
    otext = card.get("oracle_text", "")
    lines = text.split_lines(otext)
    kws = card.get("keywords", [])
    keyword_calls: list[str] = []
    todo_lines: list[str] = []
    for line in lines:
        names = _keyword_line_names(line, kws)
        if names:
            keyword_calls += names
        else:
            todo_lines.append(line)
    ident = "".join(c for c in WUBRG if c in (card.get("color_identity") or []))
    ref_notes: list[str] = []
    body_todos: list[str] = []
    for line in todo_lines:
        scored = refs.score_line(line, name, k=2, exclude=name)
        body_todos.append(f"    // {repo.TODO_MARK}: {line}")
        if scored["clauses"] and scored["score"] > scored["wholeScore"]:
            body_todos.append("    //   combines implemented pieces:")
            for c in scored["clauses"]:
                m = c["match"]
                if m:
                    body_todos.append(f"    //     ~{c['score']:.2f} \"{c['clause']}\" ← {m['card']} [{m['source']}]: {m['where']}")
                    ref_notes.append(m["card"])
        for m in scored["matches"]:
            body_todos.append(f"    //   ~{m['score']:.2f} {m['card']} [{m['source']}]: {m['where']}")
            ref_notes.append(m["card"])
    imports = ["com.wingedsheep.sdk.dsl.*", "com.wingedsheep.sdk.model.Rarity"]
    if keyword_calls:
        imports.insert(0, "com.wingedsheep.sdk.core.Keyword")
    out = ["package com.arcanatable.customcards.cards", ""]
    out += [f"import {i}" for i in imports]
    out += ["", "/**", f" * {name} — {card.get('set', '?').upper()} #{card.get('collector_number', '?')}.", " *",
            f" * {repo.SCAFFOLD_MARK}: generated by `tools/cardkit/cardkit newcard`. NOT IMPLEMENTED.",
            " * Implement every CARDKIT-TODO line with real SDK calls (docs/agents/CARD-PATTERNS.md,",
            " * docs/agents/generated/sdk-api.md), write positive and negative scenarios in the matching test,",
            " * then delete this block and every CARDKIT-TODO. If a line needs a primitive the SDK lacks, stop",
            " * and record an engine blocker (tools/cardkit/cardkit blocker) — never approximate it.",
            " */",
            f"val {val} = card({repo.kotlin_string(name)}) {{"]
    if card.get("mana_cost"):
        out.append(f"    manaCost = {repo.kotlin_string(card['mana_cost'])}")
    out.append(f"    colorIdentity = {repo.kotlin_string(ident)}")
    out.append(f"    typeLine = {repo.kotlin_string(card.get('type_line', ''))}")
    for field in ("power", "toughness"):
        v = card.get(field)
        if v is None:
            continue
        if re.fullmatch(r"-?\d+", str(v)):
            out.append(f"    {field} = {v}")
        else:
            out.append(f"    // {repo.TODO_MARK}: {field} is {v!r} (characteristic-defining): use dynamicPower/dynamicToughness")
    if card.get("loyalty") and re.fullmatch(r"\d+", str(card["loyalty"])):
        out.append(f"    startingLoyalty = {card['loyalty']}")
    out.append(f"    oracleText = {repo.kotlin_string(otext)}")
    out.append("")
    if keyword_calls:
        out.append(f"    keywords({', '.join('Keyword.' + k for k in keyword_calls)})")
        out.append("")
    if card.get("layout") in readiness.MULTI_FACE:
        out.append(f"    // {repo.TODO_MARK}: {card['layout']} layout — see `face(` / `modalBack(` in sdk-api.md")
    out += body_todos
    if body_todos:
        out.append("")
    out.append("    metadata {")
    if card.get("rarity") in RARITY:
        out.append(f"        rarity = Rarity.{RARITY[card['rarity']]}")
    if card.get("collector_number"):
        out.append(f"        collectorNumber = {repo.kotlin_string(str(card['collector_number']))}")
    if card.get("artist"):
        out.append(f"        artist = {repo.kotlin_string(card['artist'])}")
    if card.get("image_uri"):
        out.append(f"        imageUri = {repo.kotlin_string(card['image_uri'])}")
    out += ["    }", "}", ""]
    return "\n".join(out), ref_notes


def render_test(card: dict, val: str) -> str:
    name = card["name"]
    lines = text.split_lines(card.get("oracle_text", ""))
    todo = "\n".join(f"    //   - {l}" for l in lines) or "    //   - (no rules text)"
    return f"""package com.arcanatable.customcards

import com.arcanatable.customcards.cards.{val}
import com.arcanatable.customcards.support.*
import org.junit.Assert.*
import org.junit.Test

class {val}ScenarioTest {{
    // {repo.SCAFFOLD_MARK}: replace this whole test with real scenarios on the engine, e.g.
    //   val d = customScenario({val})            // a real game, card round-tripped through its JSON data
    //   val p = d.player1
    //   val card = d.putCardInHand(p, {repo.kotlin_string(name)})
    //   d.giveMana(p, Color.WHITE); d.giveColorlessMana(p, 2)
    //   assertNull(d.castSpell(p, card).error)
    //   d.resolveAll(Choices(yes = true))
    // Cover, for every line below, the positive case AND a negative/edge case (declined "may",
    // no legal target, intervening-if false, wrong controller, source gone before resolution):
{todo}
    @Test
    fun scaffoldIsNotImplementedYet() {{
        fail({repo.kotlin_string(name + " is a cardkit scaffold: implement its abilities and real scenarios first")})
    }}
}}
"""


def create(name: str, out_dir: Path | None = None, test_dir: Path | None = None, online: bool = True,
           force: bool = False) -> dict:
    state, reasons, source = readiness.implementation_state(name)
    if state == "IMPLEMENTED_AND_TESTED" and not force:
        raise SystemExit(f"{name}: already available ({'; '.join(reasons)}). Nothing to scaffold.")
    if source == "custom" and not force:
        raise SystemExit(f"{name}: a custom definition already exists ({'; '.join(reasons)}).")
    card = oracle.lookup(name, online=online)
    if not card:
        raise SystemExit(f"{name}: no Oracle record (not cached, and Scryfall {'did not find it' if online else 'lookup disabled'}).")
    val = repo.val_name_for(card["name"])
    card_dir = out_dir or repo.CARDS_DIR
    t_dir = test_dir or repo.TESTS_DIR
    card_path = card_dir / f"{val}.kt"
    test_path = t_dir / f"{val}ScenarioTest.kt"
    for p in (card_path, test_path):
        if p.exists() and not force:
            raise SystemExit(f"{repo.rel(p)} already exists; refusing to overwrite (use --force)")
    card_src, ref_cards = render_card(card, val)
    card_dir.mkdir(parents=True, exist_ok=True)
    t_dir.mkdir(parents=True, exist_ok=True)
    card_path.write_text(card_src, encoding="utf-8")
    test_path.write_text(render_test(card, val), encoding="utf-8")
    verdict = readiness.classify(card["name"])
    return {"card": card["name"], "val": val, "set": card.get("set", "").upper(), "files": [repo.rel(card_path), repo.rel(test_path)],
            "readiness": verdict["readiness"], "reasons": verdict["reasons"], "references": sorted(set(ref_cards))}
