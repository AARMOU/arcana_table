"""Index of which DSL constructs each registered, tested custom card uses.

This is the "verified in this repo" half of the cookbook: every construct listed has at least one card
that is registered in CustomCards.kt, exported to the app, and exercised by a scenario test on the real
rules engine. Regenerate with `tools/cardkit/cardkit patterns` (CI runs `--check`).
"""
from __future__ import annotations

import json
import re
from collections import defaultdict

from . import repo

OUT_MD = repo.GENERATED / "pattern-index.md"
OUT_JSON = repo.GENERATED / "pattern-index.json"

FACADES = ("Effects", "Triggers", "Conditions", "Costs", "DynamicAmounts", "Filters", "Targets", "Patterns",
           "KeywordAbility", "TargetFilter", "GameObjectFilter", "Keyword", "CounterType", "TimingRule",
           "EffectTarget", "Player", "Duration", "Step")
_FACADE_REF = re.compile(r"\b(" + "|".join(FACADES) + r")\.([A-Za-z_][\w]*(?:\.[a-z][\w]*)?)")
_BLOCK = re.compile(r"^\s{4}(triggeredAbility|activatedAbility|staticAbility|spell|replacementEffect|keywordAbility|"
                    r"keywords|equipAbility|loyaltyAbility|sagaChapter|additionalCost|stateTriggeredAbility|"
                    r"[a-z][A-Za-z]+)\s*[({]", re.M)
_STATIC = re.compile(r"\bability\s*=\s*([A-Z]\w+)\s*[(\n]")
_REPLACEMENT = re.compile(r"replacementEffect\(\s*([A-Z]\w+)")
_FIELDS = re.compile(r"^\s+(interveningIf|optional|triggerRestriction|timing|manaAbility|restrictions?|"
                     r"activationRestrictions?|condition)\s*=", re.M)
_TARGET = re.compile(r"\b(target|targets)\(")
_NOT_BLOCKS = {"metadata", "val", "if", "for", "when", "return"}

CATEGORIES = [
    ("Card structure blocks", "block"),
    ("Triggers", "Triggers"),
    ("Effects", "Effects"),
    ("Conditions", "Conditions"),
    ("Costs", "Costs"),
    ("Dynamic amounts", "DynamicAmounts"),
    ("Static abilities (`staticAbility { ability = … }`)", "static"),
    ("Replacement effects (`replacementEffect(…)`)", "replacement"),
    ("Keyword abilities (`keywordAbility(KeywordAbility.…)`)", "KeywordAbility"),
    ("Keywords (`keywords(Keyword.…)`)", "Keyword"),
    ("Targets and filters", "targeting"),
    ("Ability fields", "field"),
    ("Other facades", "other"),
]


def constructs(text: str) -> set[tuple[str, str]]:
    found: set[tuple[str, str]] = set()
    body = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r'oracleText\s*=\s*(?:"(?:[^"\\]|\\.)*"\s*\+?\s*)+', "", body)
    for m in _BLOCK.finditer(body):
        name = m.group(1)
        if name not in _NOT_BLOCKS:
            found.add(("block", name + ("()" if body[m.end() - 1] == "(" else " { }")))
    for m in _FACADE_REF.finditer(body):
        facade, member = m.groups()
        if facade in ("Triggers", "Patterns"):
            key = f"{facade}.{member}"
        else:
            key = f"{facade}.{member.split('.')[0]}"
        if facade in ("TargetFilter", "GameObjectFilter", "Targets", "Filters", "EffectTarget", "Player"):
            found.add(("targeting", key))
        elif facade in ("Effects", "Triggers", "Conditions", "Costs", "DynamicAmounts", "KeywordAbility", "Keyword"):
            found.add((facade, key))
        else:
            found.add(("other", key))
    for m in _STATIC.finditer(body):
        if not m.group(1).endswith(("Builder", "Ability")):
            found.add(("static", m.group(1)))
    for m in _REPLACEMENT.finditer(body):
        found.add(("replacement", m.group(1)))
    for m in _FIELDS.finditer(body):
        found.add(("field", m.group(1)))
    for m in _TARGET.finditer(body):
        found.add(("targeting", m.group(1) + "(…)"))
    return found


def build() -> dict:
    registered = {e.val for e in repo.registry_entries()}
    usage: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for c in repo.card_sources():
        if c.val not in registered or c.is_scaffold:
            continue
        test = repo.own_test(c.val)
        tests = repo.tests_by_val().get(c.val, [])
        if not test and not tests:
            continue
        entry = {"card": c.name, "file": repo.rel(c.path), "test": repo.rel(test or tests[0]),
                 "lines": c.text.count("\n") + 1}
        for key in constructs(c.text):
            usage[key].append(entry)
    out = {}
    for (cat, key), cards in usage.items():
        cards = sorted(cards, key=lambda e: (e["lines"], e["card"]))
        out.setdefault(cat, {})[key] = {"count": len(cards), "examples": cards[:6]}
    return out


def render_md(data: dict) -> str:
    lines = [
        "# Verified pattern index (generated)",
        "",
        "<!-- Generated by `tools/cardkit/cardkit patterns`. Do not edit by hand. -->",
        "",
        "Every construct below is used by at least one custom card that is **registered, exported and",
        "covered by a scenario test** on the real engine. Open the shortest example first; copy its shape and",
        "its test. Count = number of tested cards using it. For hand-written walkthroughs see",
        "[`../CARD-PATTERNS.md`](../CARD-PATTERNS.md); for whether a member exists at all, see",
        "[`sdk-api.md`](sdk-api.md).",
        "",
    ]
    for title, cat in CATEGORIES:
        items = data.get(cat, {})
        if not items:
            continue
        lines += [f"## {title}", "", "| Construct | Tested cards | Shortest examples (card → test) |", "|---|---:|---|"]
        for key in sorted(items, key=lambda k: (-items[k]["count"], k.casefold())):
            ex = items[key]["examples"][:3]
            cells = "<br>".join(f"[{e['card']}](../../../{e['file']}) → [test](../../../{e['test']})" for e in ex)
            lines.append(f"| `{key}` | {items[key]['count']} | {cells} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write(check: bool = False) -> bool:
    data = build()
    md = render_md(data)
    js = json.dumps(data, indent=1, sort_keys=True) + "\n"
    if check:
        return OUT_MD.exists() and OUT_MD.read_text(encoding="utf-8") == md and \
            OUT_JSON.exists() and OUT_JSON.read_text(encoding="utf-8") == js
    repo.GENERATED.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text(md, encoding="utf-8")
    OUT_JSON.write_text(js, encoding="utf-8")
    return True


def examples_for(cards_text: str, limit: int = 3) -> list[dict]:
    """Tested example cards that share constructs with [cards_text] (used by the scaffolder)."""
    data = json.loads(OUT_JSON.read_text(encoding="utf-8")) if OUT_JSON.exists() else build()
    wanted = constructs(cards_text)
    seen, out = set(), []
    for cat, key in sorted(wanted):
        for e in data.get(cat, {}).get(key, {}).get("examples", [])[:1]:
            if e["card"] not in seen:
                seen.add(e["card"])
                out.append({**e, "construct": key})
    return out[:limit]
