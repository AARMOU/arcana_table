/* Arcana Control: owner briefing (Work tab). Read-only.
 * Source: the pinned "Current orders & owner decisions" issue that Claude PM keeps current.
 * Parses its markdown into plain sections and renders them with DOM nodes only (never innerHTML). */
(function (root) {
  'use strict';
  const ORDERS_ISSUE = 883;
  const STALE_MS = 36 * 3600 * 1000;

  // ---- pure parsing (tested in orders-page.test.cjs) ----
  function inline(md) {
    const out = [];
    const re = /\[([^\]]+)\]\((https:\/\/[^)\s]+)\)|\*\*([^*]+)\*\*|`([^`]+)`/g;
    let last = 0, m;
    const s = String(md || '');
    while ((m = re.exec(s))) {
      if (m.index > last) out.push({ t: 'text', v: s.slice(last, m.index) });
      if (m[1] !== undefined) out.push({ t: 'a', v: m[1], href: m[2] });
      else if (m[3] !== undefined) out.push({ t: 'b', v: m[3] });
      else out.push({ t: 'code', v: m[4] });
      last = re.lastIndex;
    }
    if (last < s.length) out.push({ t: 'text', v: s.slice(last) });
    return out;
  }
  function plain(md) { return inline(md).map(p => p.v).join(''); }
  function cells(line) {
    return line.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map(c => c.trim());
  }
  function parse(body) {
    const text = String(body || '').replace(/\r/g, '');
    const meta = {};
    const rev = text.match(/Revision\s+(\d+)/i); if (rev) meta.revision = Number(rev[1]);
    const upd = text.match(/\*\*Updated:\*\*\s*([0-9-]+\s+[0-9:]+\s*UTC)/i);
    if (upd) meta.updated = upd[1];
    const sections = [];
    let cur = null;
    for (const raw of text.split('\n')) {
      const line = raw.trimEnd();
      const h = line.match(/^##\s+(?:\d+\.\s*)?(.+)$/);
      if (h) { cur = { title: h[1].trim(), items: [], table: null, paras: [] }; sections.push(cur); continue; }
      if (!cur || /^---\s*$/.test(line) || /^_Generated by/.test(line)) { if (/^---\s*$/.test(line)) cur = null; continue; }
      if (/^\s*\|/.test(line)) {
        const row = cells(line);
        if (row.every(c => /^:?-{2,}:?$/.test(c))) continue;
        if (!cur.table) cur.table = { head: row, rows: [] }; else cur.table.rows.push(row);
      } else if (/^\s*[-*]\s+/.test(line)) cur.items.push(line.replace(/^\s*[-*]\s+/, ''));
      else if (line.trim()) cur.paras.push(line.trim());
    }
    return { meta, sections };
  }
  function kind(title) {
    const t = title.toLowerCase();
    if (t.includes('waiting on')) return 'waiting';
    if (t.includes('decision')) return 'decisions';
    if (t.includes('order')) return 'orders';
    if (t.includes('done')) return 'done';
    return 'other';
  }
  function statusTag(status) {
    const s = plain(status).toLowerCase();
    if (/\bblocked|failed|stuck/.test(s)) return { tag: 'red', label: 'Blocked' };
    if (/\bdone|merged|complete/.test(s)) return { tag: 'green', label: 'Done' };
    if (/parked|on hold|benched/.test(s)) return { tag: 'gray', label: 'Parked' };
    if (/queued|next|after|waiting/.test(s)) return { tag: 'blue', label: 'Up next' };
    if (/picked up|ongoing|daily|working|in progress/.test(s)) return { tag: 'amber', label: 'Working' };
    return { tag: 'gray', label: plain(status).slice(0, 24) || 'Unknown' };
  }
  function agentBadge(agent) {
    const a = plain(agent).toLowerCase();
    if (a.includes('gsd')) return { cls: 'claude', mark: 'GS' };
    if (a.includes('claude')) return { cls: 'claude', mark: 'CL' };
    if (a.includes('copilot')) return { cls: 'copilot', mark: 'CO' };
    if (a.includes('goose')) return { cls: 'goose', mark: '🪿' };
    if (a.includes('bone')) return { cls: 'bone', mark: 'BK' };
    return { cls: 'none', mark: '·' };
  }
  function isRulesQuestion(issue) {
    return issue && !issue.pull_request && issue.state !== 'closed' &&
      /^❓\s*Rules question/i.test(String(issue.title || ''));
  }
  function rulesCard(title) {
    return String(title || '').replace(/^❓\s*Rules question\s*:?\s*/i, '').trim() || 'Card';
  }

  // ---- rendering ----
  function render(doc, container, issue, openIssues, now) {
    now = now || Date.now();
    const el = (tag, cls, value) => { const n = doc.createElement(tag); if (cls) n.className = cls; if (value !== undefined) n.textContent = value; return n; };
    const rich = (md, tag, cls) => {
      const n = el(tag || 'span', cls);
      for (const p of inline(md)) {
        if (p.t === 'a') { const a = el('a', 'ob-link', p.v); a.href = p.href; a.target = '_blank'; a.rel = 'noopener noreferrer'; n.append(a); }
        else if (p.t === 'b') n.append(el('strong', '', p.v));
        else if (p.t === 'code') n.append(el('code', '', p.v));
        else n.append(doc.createTextNode(p.v));
      }
      return n;
    };
    const label = (title, hint) => { const d = el('div', 'section-label'); d.append(el('h2', '', title)); if (hint) d.append(el('span', 'hint', hint)); return d; };
    container.replaceChildren();
    if (!issue || typeof issue.body !== 'string') {
      container.append(el('div', 'empty', 'Owner briefing unavailable right now. Pull to refresh, or ask Claude or GPT for the current orders.'));
      return { ok: false };
    }
    const { meta, sections } = parse(issue.body);
    const updatedAt = Date.parse(issue.updated_at);
    const stale = Number.isFinite(updatedAt) && now - updatedAt > STALE_MS;
    const by = k => sections.filter(s => kind(s.title) === k);

    // 1. Waiting on you
    const waiting = by('waiting').flatMap(s => s.items);
    const wbox = el('div', 'safety-box ob-waiting' + (waiting.length ? '' : ' clear'));
    wbox.append(el('h3', '', 'Waiting on you'));
    wbox.append(el('div', 'big', waiting.length ? waiting.length + (waiting.length === 1 ? ' thing' : ' things') : 'Nothing right now'));
    if (waiting.length) { const ul = el('ul', 'ob-list'); waiting.forEach(w => ul.append(rich(w, 'li'))); wbox.append(ul); }
    wbox.append(el('p', 'fine', 'Answer in Claude or GPT, whichever you have open. Either one will act on it.'));
    container.append(wbox);

    // 2. Rules questions
    const rq = (Array.isArray(openIssues) ? openIssues : []).filter(isRulesQuestion);
    container.append(label('Card rules questions', rq.length ? rq.length + ' open' : 'None open'));
    const rqPanel = el('section', 'panel'); const rqRows = el('div', 'rows');
    if (!rq.length) rqRows.append(el('div', 'empty', 'No open rules questions. When a worker needs your call on how a card works, it shows up here.'));
    rq.forEach(i => {
      const row = el('div', 'list-row'); row.append(el('span', 'row-icon running', '?'));
      const main = el('div', 'row-main'); main.append(el('div', 'row-title', rulesCard(i.title)));
      main.append(el('div', 'row-sub', 'Asked ' + ago(i.created_at, now) + ' · answer in Claude or GPT'));
      row.append(main); row.append(el('span', 'tag amber', 'Needs you')); rqRows.append(row);
    });
    rqPanel.append(rqRows); container.append(rqPanel);

    // 3. Who is doing what
    for (const s of by('orders')) {
      const t = s.table; if (!t) continue;
      const col = name => t.head.findIndex(h => h.toLowerCase() === name);
      const ia = col('agent'), io = col('order'), is = col('status'), id = col('id');
      container.append(label('Who is doing what', t.rows.length + ' orders'));
      const grid = el('div', 'ob-orders');
      t.rows.forEach(r => {
        const badge = agentBadge(r[ia]); const st = statusTag(r[is] || '');
        const card = el('div', 'ob-order');
        const top = el('div', 'lane-top');
        top.append(el('span', 'avatar ' + badge.cls, badge.mark));
        top.append(el('span', 'tag ' + st.tag, st.label));
        card.append(top);
        card.append(el('h3', '', plain(r[ia] || '')));
        card.append(rich(r[io] || '', 'p'));
        card.append(rich((id >= 0 && r[id] ? r[id] + ' · ' : '') + (r[is] || ''), 'span', 'lane-status'));
        grid.append(card);
      });
      container.append(grid);
    }

    // 4. Any other sections the PM adds (deck progress, latest test build, ...)
    for (const s of sections.filter(x => kind(x.title) === 'other')) {
      container.append(label(plain(s.title)));
      const p = el('section', 'panel ob-generic');
      s.paras.forEach(x => p.append(rich(x, 'p')));
      if (s.items.length) { const ul = el('ul', 'ob-list'); s.items.forEach(x => ul.append(rich(x, 'li'))); p.append(ul); }
      if (s.table) {
        const wrap = el('div', 'ob-table-wrap'); const tbl = el('table', 'ob-table');
        const hr = el('tr'); s.table.head.forEach(h => hr.append(rich(h, 'th'))); tbl.append(hr);
        s.table.rows.forEach(r => { const tr = el('tr'); r.forEach(c => tr.append(rich(c, 'td'))); tbl.append(tr); });
        wrap.append(tbl); p.append(wrap);
      }
      container.append(p);
    }

    // 5. Done recently
    const done = by('done').flatMap(s => s.items);
    if (done.length) {
      container.append(label('Done recently'));
      const p = el('section', 'panel ob-generic'); const ul = el('ul', 'ob-list'); done.forEach(x => ul.append(rich(x, 'li'))); p.append(ul); container.append(p);
    }

    // 6. Standing decisions (collapsed)
    const dec = by('decisions').flatMap(s => s.items);
    if (dec.length) {
      const det = el('details', 'ob-details');
      det.append(el('summary', '', 'Your standing decisions (' + dec.length + ')'));
      const ul = el('ul', 'ob-list'); dec.forEach(x => ul.append(rich(x, 'li'))); det.append(ul);
      container.append(det);
    }
    return { ok: true, stale, revision: meta.revision, updated: issue.updated_at, waiting: waiting.length, rules: rq.length };
  }
  function ago(input, now) {
    const t = Date.parse(input); if (!Number.isFinite(t)) return 'at an unknown time';
    const n = Math.max(0, Math.floor((now - t) / 60000));
    if (n < 1) return 'just now'; if (n < 60) return n + 'm ago'; if (n < 1440) return Math.floor(n / 60) + 'h ago'; return Math.floor(n / 1440) + 'd ago';
  }

  const api = { ORDERS_ISSUE, STALE_MS, inline, plain, parse, kind, statusTag, agentBadge, isRulesQuestion, rulesCard, render, ago };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.ArcanaOrders = api;
})(typeof window !== 'undefined' ? window : globalThis);
